from __future__ import annotations

from collections import OrderedDict

import torch
from torch import nn

from .dit import DiffusionTransformer
from .gating import multimodal_change_gates, observable_contact_gate
from .tokenizers import DecodedFrames, MultimodalFrameTokenizer


class PulseWorldVLA(nn.Module):
    """Joint latent world model and action policy for pulse pre-approach.

    The same latent frame schema is used on both sides of the model. History
    frames are clean conditions; every future modality, including the action,
    is generated by one rectified-flow Diffusion Transformer.
    """

    def __init__(
        self,
        image_size=(128, 128),
        tactile_size=(32, 32),
        observation_horizon=2,
        prediction_horizon=4,
        state_dim=12,
        proximity_dim=5,
        action_dim=3,
        vision_latent_channels=8,
        tactile_latent_channels=4,
        latent_token_width=16,
        model_dim=256,
        layers=8,
        heads=8,
        dropout=0.0,
        condition_dropout=0.1,
        modality_loss_weights=None,
        attention_gate_scale=2.0,
        modality_noise_scales=None,
        action_endpoint_loss_weight=2.0,
        predict_vector_residuals=False,
        contact_gated_pressure=False,
        action_channel_loss_weights=None,
        direct_action_head_weight=0.0,
        direct_action_residual_scale=0.5,
        direct_action_direction_loss_weight=0.0,
        direct_action_direction_scale=None,
        direct_action_phase_loss_weights=None,
        direct_numeric_bypass=False,
        direct_numeric_mode="residual",
        direct_numeric_tactile_summary=False,
        direct_numeric_tactile_fingers=2,
        direct_numeric_contact_fingers=0,
        direct_numeric_feature_mean=None,
        direct_numeric_feature_std=None,
        direct_numeric_standardization_clip=0.0,
        full_hand_tactile=False,
        fusion_mode="legacy",
    ):
        super().__init__()
        self.observation_horizon = int(observation_horizon)
        self.prediction_horizon = int(prediction_horizon)
        self.condition_dropout = float(condition_dropout)
        self.action_endpoint_loss_weight = float(action_endpoint_loss_weight)
        self.predict_vector_residuals = bool(predict_vector_residuals)
        self.contact_gated_pressure = bool(contact_gated_pressure)
        if fusion_mode not in {
            "legacy",
            "vanilla",
            "tactile_gate",
            "contact_attention_bias",
        }:
            raise ValueError(f"unsupported fusion mode: {fusion_mode}")
        self.fusion_mode = str(fusion_mode)
        self.direct_action_head_weight = float(direct_action_head_weight)
        self.direct_action_direction_loss_weight = float(
            direct_action_direction_loss_weight
        )
        direct_scale = torch.as_tensor(
            direct_action_residual_scale, dtype=torch.float32
        )
        if direct_scale.ndim == 0:
            direct_scale = direct_scale.repeat(action_dim)
        if direct_scale.shape != (action_dim,) or torch.any(
            direct_scale <= 0
        ):
            raise ValueError(
                "direct_action_residual_scale must be a positive scalar or "
                f"shape ({action_dim},)"
            )
        self.register_buffer(
            "direct_action_residual_scale",
            direct_scale,
            persistent=False,
        )
        direction_scale = torch.as_tensor(
            (
                [1.0] * action_dim
                if direct_action_direction_scale is None
                else direct_action_direction_scale
            ),
            dtype=torch.float32,
        )
        if direction_scale.shape != (action_dim,) or torch.any(
            direction_scale <= 0
        ):
            raise ValueError(
                "direct_action_direction_scale must contain one positive "
                "value per action channel"
            )
        self.register_buffer(
            "direct_action_direction_scale",
            direction_scale,
            persistent=False,
        )
        phase_weights = torch.as_tensor(
            (
                []
                if direct_action_phase_loss_weights is None
                else direct_action_phase_loss_weights
            ),
            dtype=torch.float32,
        )
        if phase_weights.ndim != 1 or torch.any(phase_weights <= 0):
            raise ValueError(
                "direct_action_phase_loss_weights must be a one-dimensional "
                "sequence of positive values"
            )
        self.register_buffer(
            "direct_action_phase_loss_weights",
            phase_weights,
            persistent=False,
        )
        if self.direct_action_head_weight < 0:
            raise ValueError("direct_action_head_weight must be non-negative")
        if self.direct_action_direction_loss_weight < 0:
            raise ValueError(
                "direct_action_direction_loss_weight must be non-negative"
            )
        self.action_channel_loss_weights = (
            None
            if action_channel_loss_weights is None
            else tuple(float(value) for value in action_channel_loss_weights)
        )
        if (
            self.action_channel_loss_weights is not None
            and len(self.action_channel_loss_weights) != action_dim
        ):
            raise ValueError(
                "action_channel_loss_weights must match action_dim"
            )
        self.tokenizer = MultimodalFrameTokenizer(
            tuple(image_size),
            tuple(tactile_size),
            vision_latent_channels,
            tactile_latent_channels,
            proximity_dim,
            state_dim,
            action_dim,
            latent_token_width,
            full_hand_tactile=full_hand_tactile,
        )
        self.transformer = DiffusionTransformer(
            input_dim=latent_token_width,
            model_dim=model_dim,
            layers=layers,
            heads=heads,
            maximum_frames=observation_horizon + prediction_horizon,
            maximum_tokens_per_frame=self.tokenizer.layout.tokens_per_frame,
            dropout=dropout,
            attention_gate_scale=attention_gate_scale,
        )
        self.direct_action_head = None
        self.direct_numeric_head = None
        self.direct_numeric_mode = str(direct_numeric_mode)
        self.direct_numeric_tactile_summary = bool(
            direct_numeric_tactile_summary
        )
        self.direct_numeric_tactile_fingers = int(
            direct_numeric_tactile_fingers
        )
        if self.direct_numeric_tactile_fingers < 1:
            raise ValueError("direct numeric tactile finger count must be positive")
        self.direct_numeric_contact_fingers = int(
            direct_numeric_contact_fingers
        )
        if not 0 <= self.direct_numeric_contact_fingers <= 5:
            raise ValueError("direct numeric contact finger count must be in [0, 5]")
        self.direct_numeric_standardization_clip = float(
            direct_numeric_standardization_clip
        )
        if self.direct_numeric_standardization_clip < 0.0:
            raise ValueError("numeric standardization clip must be non-negative")
        self.register_buffer(
            "direct_numeric_feature_mean",
            torch.as_tensor(
                [] if direct_numeric_feature_mean is None else direct_numeric_feature_mean,
                dtype=torch.float32,
            ),
            persistent=False,
        )
        self.register_buffer(
            "direct_numeric_feature_std",
            torch.as_tensor(
                [] if direct_numeric_feature_std is None else direct_numeric_feature_std,
                dtype=torch.float32,
            ),
            persistent=False,
        )
        if self.direct_numeric_mode not in {"residual", "override"}:
            raise ValueError("direct_numeric_mode must be residual or override")
        if self.direct_action_head_weight > 0:
            pooled_modalities = len(self.tokenizer.layout.slices())
            direct_input = (
                observation_horizon * pooled_modalities * latent_token_width
            )
            self.direct_action_head = nn.Sequential(
                nn.Linear(direct_input, model_dim),
                nn.LayerNorm(model_dim),
                nn.SiLU(),
                nn.Linear(model_dim, model_dim),
                nn.SiLU(),
                nn.Linear(model_dim, prediction_horizon * action_dim),
                nn.Tanh(),
            )
            # Start from the repeat-last-action residual prior.
            nn.init.zeros_(self.direct_action_head[-2].weight)
            nn.init.zeros_(self.direct_action_head[-2].bias)
            if direct_numeric_bypass:
                numeric_width = (
                    proximity_dim + state_dim + action_dim + 1
                )
                if self.direct_numeric_tactile_summary:
                    # Per-finger mean and peak pressure. The legacy official
                    # hand uses two pads; CH5's active view uses three. Keep
                    # the count explicit so neither path silently blends two
                    # anatomical fingers into one feature band.
                    numeric_width += 2 * self.direct_numeric_tactile_fingers
                numeric_width += self.direct_numeric_contact_fingers
                self.direct_numeric_head = nn.Linear(
                    observation_horizon * numeric_width,
                    prediction_horizon * action_dim,
                )
                feature_width = observation_horizon * numeric_width
                if self.direct_numeric_feature_mean.numel() not in {
                    0,
                    feature_width,
                } or self.direct_numeric_feature_std.numel() not in {
                    0,
                    feature_width,
                }:
                    raise ValueError(
                        "direct numeric normalization must match flattened feature width"
                    )
                if self.direct_numeric_feature_mean.numel() != (
                    self.direct_numeric_feature_std.numel()
                ):
                    raise ValueError(
                        "direct numeric mean/std must both be present or absent"
                    )
                if self.direct_numeric_feature_std.numel() and torch.any(
                    self.direct_numeric_feature_std <= 0
                ):
                    raise ValueError("direct numeric feature std must be positive")
                nn.init.zeros_(self.direct_numeric_head.weight)
                nn.init.zeros_(self.direct_numeric_head.bias)
        weights = modality_loss_weights or {
            "vision": 1.0,
            "tactile": 2.0,
            "proximity": 1.5,
            "state": 1.0,
            "action": 4.0,
        }
        self.modality_loss_weights = {key: float(value) for key, value in weights.items()}
        self.modality_noise_scales = modality_noise_scales or {
            "vision": 1.0, "tactile": 1.0, "full_hand_tactile": 1.0,
            "proximity": 1.0, "state": 1.0, "action": 1.0
        }

    def _noise_scale(self, device, dtype):
        layout = self.tokenizer.layout
        scale = torch.ones(layout.tokens_per_frame, layout.token_width, device=device, dtype=dtype)
        for name, slots in layout.slices().items():
            scale[slots] *= float(self.modality_noise_scales.get(name, 1.0))
        return scale

    def _change_gates(self, observation):
        if self.fusion_mode == "vanilla":
            return None
        gates = multimodal_change_gates(observation)
        if self.fusion_mode == "contact_attention_bias":
            gates["tactile"] = observable_contact_gate(observation)
        return gates

    def _apply_vector_residuals(self, values, observation, inverse=False):
        if not self.predict_vector_residuals:
            return values
        values = values.clone()
        layout = self.tokenizer.layout
        sign = 1.0 if inverse else -1.0
        specifications = (
            ("proximity", layout.proximity_index, layout.proximity_dim),
            ("robot_state", layout.state_index, layout.state_dim),
            ("action", layout.action_index, layout.action_dim),
        )
        for name, slot, width in specifications:
            base = observation[name][:, -1, :width]
            values[:, :, slot, :width] += sign * base[:, None]
        return values

    def _sequence_metadata(self, context_frames: int, future_frames: int, device):
        layout = self.tokenizer.layout
        frames = context_frames + future_frames
        modality = layout.modality_ids(device).repeat(frames)
        frame = torch.arange(frames, device=device).repeat_interleave(layout.tokens_per_frame)
        slot = torch.arange(layout.tokens_per_frame, device=device).repeat(frames)
        known = frame.lt(context_frames)
        return modality, frame, slot, known

    def _predict_direct_action(self, context, observation):
        if self.direct_action_head is None:
            raise RuntimeError("direct action head is not enabled")
        pooled = []
        for slots in context.layout.slices().values():
            values = context.values[:, :, slots]
            valid = context.valid_mask[:, :, slots].to(values.dtype)
            pooled.append(
                (values * valid[..., None]).sum(dim=2)
                / valid.sum(dim=2, keepdim=True).clamp_min(1)
            )
        features = torch.cat(pooled, dim=-1).flatten(1)
        delta = self.direct_action_head(features).unflatten(
            1, (self.prediction_horizon, context.layout.action_dim)
        )
        previous = observation["action"][:, -1, : context.layout.action_dim]
        action = torch.clamp(
            previous[:, None]
            + self.direct_action_residual_scale[None, None] * delta,
            min=-1.0,
            max=1.0,
        )
        if self.direct_numeric_head is not None:
            task_phase = observation.get("task_phase")
            if task_phase is None or task_phase.shape != previous.shape[:1] + (
                self.observation_horizon,
            ):
                raise ValueError(
                    "direct numeric bypass requires observation task_phase [batch, time]"
                )
            phase_scale = max(1, self.direct_action_phase_loss_weights.numel() - 1)
            if phase_scale == 1:
                phase_scale = 13
            numeric = torch.cat(
                [
                    observation["proximity"],
                    observation["robot_state"],
                    observation["action"],
                    task_phase.to(action.dtype)[..., None] / float(phase_scale),
                ]
                + (
                    [self._numeric_contact_state(observation)]
                    if self.direct_numeric_contact_fingers
                    else []
                )
                + (
                    [self._numeric_tactile_summary(observation["tactile"])]
                    if self.direct_numeric_tactile_summary
                    else []
                ),
                dim=-1,
            ).flatten(1)
            if self.direct_numeric_feature_mean.numel():
                numeric = (
                    numeric - self.direct_numeric_feature_mean[None]
                ) / self.direct_numeric_feature_std[None]
                if self.direct_numeric_standardization_clip > 0.0:
                    numeric = torch.clamp(
                        numeric,
                        -self.direct_numeric_standardization_clip,
                        self.direct_numeric_standardization_clip,
                    )
            numeric_action = self.direct_numeric_head(numeric).unflatten(
                1, (self.prediction_horizon, context.layout.action_dim)
            )
            if self.direct_numeric_mode == "override":
                action = torch.clamp(numeric_action, min=-1.0, max=1.0)
            else:
                action = torch.clamp(action + numeric_action, min=-1.0, max=1.0)
        if self.contact_gated_pressure and context.layout.action_dim >= 7:
            action = action.clone()
            contact = observation["tactile_valid"][:, -1].to(action.dtype)
            action[:, :, 6] *= contact[:, None]
        return action

    def _numeric_contact_state(self, observation: dict) -> torch.Tensor:
        contact = observation.get("diagnostic_contact")
        expected = self.direct_numeric_contact_fingers
        if contact is None or contact.ndim != 3 or contact.shape[-1] != expected:
            raise ValueError(
                "direct numeric contact state requires "
                f"[batch,time,{expected}]"
            )
        return contact.to(dtype=observation["action"].dtype)

    def _numeric_tactile_summary(self, tactile: torch.Tensor) -> torch.Tensor:
        """Return one mean/peak pair for each configured active finger."""
        if tactile.ndim != 5 or tactile.shape[2] != 1:
            raise ValueError(
                "numeric tactile summary requires [batch,time,1,height,width]"
            )
        height = int(tactile.shape[3])
        if height < self.direct_numeric_tactile_fingers:
            raise ValueError(
                "numeric tactile summary has fewer rows than active fingers"
            )
        fingers = torch.tensor_split(
            tactile[:, :, 0], self.direct_numeric_tactile_fingers, dim=-2
        )
        values = []
        for finger in fingers:
            values.extend(
                (
                    finger.mean(dim=(-2, -1)),
                    finger.amax(dim=(-2, -1)),
                )
            )
        return torch.stack(values, dim=-1)

    def _predict_velocity(
        self,
        context,
        noisy_future: torch.Tensor,
        future_valid: torch.Tensor,
        timestep: torch.Tensor,
        text_ids: torch.Tensor,
        drop_condition: bool = False,
        change_gates: dict[str, torch.Tensor] | None = None,
        prefix_cache: torch.Tensor | None = None,
        cache_depth: int = 0,
        return_prefix_cache: bool = False,
    ) -> torch.Tensor:
        context_tokens, context_valid = context.flattened()
        batch, future_time, future_slots, width = noisy_future.shape
        future_tokens = noisy_future.reshape(batch, future_time * future_slots, width)
        future_valid = future_valid.reshape(batch, future_time * future_slots)
        if drop_condition:
            context_tokens = torch.zeros_like(context_tokens)
            context_valid = torch.zeros_like(context_valid)
            text_ids = torch.zeros_like(text_ids)
            if change_gates:
                change_gates = {key: torch.zeros_like(value) for key, value in change_gates.items()}
        tokens = torch.cat((context_tokens, future_tokens), dim=1)
        valid = torch.cat((context_valid, future_valid), dim=1)
        metadata = self._sequence_metadata(context.values.shape[1], future_time, tokens.device)
        predicted = self.transformer(
            tokens,
            valid,
            *metadata,
            timestep,
            text_ids,
            context_token_count=context_tokens.shape[1],
            change_gates=change_gates,
            prefix_cache=prefix_cache,
            cache_depth=cache_depth,
            return_prefix_cache=return_prefix_cache,
        )
        if return_prefix_cache:
            predicted, new_cache = predicted
            return predicted[:, context_tokens.shape[1] :].reshape_as(noisy_future), new_cache
        return predicted[:, context_tokens.shape[1] :].reshape_as(noisy_future)

    def diffusion_loss(self, batch: dict[str, dict[str, torch.Tensor]], detach_tokenizer=True):
        context = self.tokenizer.encode(
            batch["observation"],
            detach_autoencoder=detach_tokenizer,
            detach_structured_tactile=False,
        )
        # The reconstruction objective updates the tokenizer. Diffusion targets
        # stay stop-gradient so the encoder cannot reduce loss by moving labels.
        target = self.tokenizer.encode(batch["future"], detach_autoencoder=True)
        target_values = self._apply_vector_residuals(target.values, batch["observation"])
        noise_scale = self._noise_scale(target_values.device, target_values.dtype)
        noise = torch.randn_like(target_values) * noise_scale[None, None]
        # Logit-normal time sampling spends more updates in the difficult middle
        # of the flow while still covering clean/noisy endpoints.
        timestep = torch.sigmoid(
            torch.randn(
                target_values.shape[0], device=target_values.device, dtype=target_values.dtype
            )
        )
        mixed = (1 - timestep[:, None, None, None]) * noise + timestep[:, None, None, None] * target_values
        drop = self.training and torch.rand((), device=mixed.device).item() < self.condition_dropout
        prediction = self._predict_velocity(
            context,
            mixed,
            target.valid_mask,
            timestep,
            batch["text_ids"],
            drop_condition=drop,
            change_gates=self._change_gates(batch["observation"]),
        )
        error = (prediction - (target_values - noise)).square()
        losses = OrderedDict()
        for name, slots in target.layout.slices().items():
            mask = target.loss_mask[:, :, slots]
            if name == "action" and self.action_channel_loss_weights is not None:
                channel_weights = torch.ones(
                    target.layout.token_width,
                    device=mask.device,
                    dtype=mask.dtype,
                )
                channel_weights[: target.layout.action_dim] = torch.as_tensor(
                    self.action_channel_loss_weights,
                    device=mask.device,
                    dtype=mask.dtype,
                )
                mask = mask * channel_weights
            value = (error[:, :, slots] * mask).sum() / mask.sum().clamp_min(1)
            losses[name] = value
        total = sum(
            self.modality_loss_weights.get(name, 1.0) * value
            for name, value in losses.items()
        )
        predicted_clean = mixed + (1 - timestep[:, None, None, None]) * prediction
        action_slot = target.layout.action_index
        predicted_endpoint = predicted_clean[:, :, action_slot, : target.layout.action_dim].sum(dim=1)
        target_endpoint = target_values[:, :, action_slot, : target.layout.action_dim].sum(dim=1)
        endpoint_error = nn.functional.smooth_l1_loss(
            predicted_endpoint, target_endpoint, reduction="none"
        )
        if self.action_channel_loss_weights is None:
            endpoint_loss = endpoint_error.mean()
        else:
            endpoint_weights = torch.as_tensor(
                self.action_channel_loss_weights,
                device=endpoint_error.device,
                dtype=endpoint_error.dtype,
            )
            endpoint_loss = (
                endpoint_error * endpoint_weights
            ).sum() / endpoint_weights.sum().clamp_min(1)
        losses["action_endpoint"] = endpoint_loss
        total = total + self.action_endpoint_loss_weight * endpoint_loss
        if self.direct_action_head is not None:
            direct_loss, direction_loss = self._direct_action_losses_from_context(
                context, batch
            )
            losses["direct_action"] = direct_loss
            losses["direct_action_direction"] = direction_loss
            total = (
                total
                + self.direct_action_head_weight * direct_loss
                + self.direct_action_direction_loss_weight * direction_loss
            )
        losses["diffusion"] = total
        return losses

    def _direct_action_losses_from_context(self, context, batch):
        direct_action = self._predict_direct_action(
            context, batch["observation"]
        )
        direct_error = nn.functional.smooth_l1_loss(
            direct_action,
            batch["future"]["action"],
            reduction="none",
        )
        phase_weights = torch.ones_like(direct_error[..., 0])
        if self.direct_action_phase_loss_weights.numel():
            task_phase = batch["future"].get("task_phase")
            if task_phase is None or task_phase.shape != direct_error.shape[:2]:
                raise ValueError(
                    "phase-weighted direct loss requires future task_phase [batch, time]"
                )
            task_phase = task_phase.long()
            if torch.any(task_phase < 0) or torch.any(
                task_phase >= self.direct_action_phase_loss_weights.numel()
            ):
                raise ValueError("future task_phase is outside configured phase weights")
            phase_weights = self.direct_action_phase_loss_weights[task_phase].to(
                dtype=direct_error.dtype
            )
        if self.action_channel_loss_weights is None:
            direct_loss = (
                direct_error * phase_weights[..., None]
            ).sum() / (
                phase_weights.sum() * direct_error.shape[-1]
            ).clamp_min(1)
        else:
            direct_weights = torch.as_tensor(
                self.action_channel_loss_weights,
                device=direct_error.device,
                dtype=direct_error.dtype,
            )
            direct_loss = (
                direct_error * direct_weights * phase_weights[..., None]
            ).sum() / (
                direct_weights.sum()
                * phase_weights.sum()
            ).clamp_min(1)
        scale = self.direct_action_direction_scale[:6].to(
            device=direct_action.device, dtype=direct_action.dtype
        )
        predicted_motion = direct_action[..., :6] * scale
        target_motion = batch["future"]["action"][..., :6] * scale
        target_norm = torch.linalg.vector_norm(target_motion, dim=-1)
        active = target_norm > 1e-8
        cosine = nn.functional.cosine_similarity(
            predicted_motion, target_motion, dim=-1, eps=1e-8
        )
        direction_error = 1.0 - cosine
        direction_loss = (
            (
                direction_error[active] * phase_weights[active]
            ).sum()
            / phase_weights[active].sum().clamp_min(1)
            if torch.any(active)
            else direct_loss.new_zeros(())
        )
        return direct_loss, direction_loss

    def direct_action_loss(self, batch, detach_tokenizer=True):
        """Train/evaluate only the low-latency direct head.

        This skips diffusion-transformer and decoder work. It is used for
        focused repairs initialized from a jointly trained checkpoint.
        """
        if self.direct_action_head is None:
            raise RuntimeError("direct action head is not enabled")
        context = self.tokenizer.encode(
            batch["observation"], detach_autoencoder=detach_tokenizer
        )
        direct_loss, direction_loss = self._direct_action_losses_from_context(
            context, batch
        )
        return (
            direct_loss
            + self.direct_action_direction_loss_weight * direction_loss
        )

    def autoencoder_loss(self, batch: dict[str, dict[str, torch.Tensor]]):
        observations, future = batch["observation"], batch["future"]
        vision = torch.cat((observations["vision"], future["vision"]), dim=1)
        tactile = torch.cat((observations["tactile"], future["tactile"]), dim=1)
        tactile_valid = torch.cat((observations["tactile_valid"], future["tactile_valid"]), dim=1)
        return {
            "vision_reconstruction": self.tokenizer.vision_autoencoder.reconstruction_loss(vision),
            "tactile_reconstruction": self.tokenizer.tactile_autoencoder.reconstruction_loss(
                tactile, tactile_valid
            ),
        }

    @torch.no_grad()
    def predict_direct_action(
        self, observation: dict[str, torch.Tensor]
    ) -> torch.Tensor:
        """Predict an action chunk without running iterative denoising.

        The joint diffusion branch remains available for future-modal world
        prediction; this path is intended for low-latency receding-horizon
        control when the optional direct residual head was trained.
        """
        context = self.tokenizer.encode(observation, detach_autoencoder=True)
        return self._predict_direct_action(context, observation)

    @torch.no_grad()
    def sample(
        self,
        observation: dict[str, torch.Tensor],
        text_ids: torch.Tensor,
        steps: int = 8,
        guidance_scale: float = 1.0,
        cache_refresh_steps: set[int] | None = None,
        cache_depth: int = 0,
        deterministic_action: bool = False,
        use_direct_action: bool = False,
        initial_action_chunk: torch.Tensor | None = None,
        action_prior_noise_scale: float = 0.1,
    ) -> DecodedFrames:
        context = self.tokenizer.encode(observation, detach_autoencoder=True)
        batch = context.values.shape[0]
        layout = context.layout
        values = torch.randn(
            batch,
            self.prediction_horizon,
            layout.tokens_per_frame,
            layout.token_width,
            device=context.values.device,
            dtype=context.values.dtype,
        )
        values = values * self._noise_scale(values.device, values.dtype)[None, None]
        if initial_action_chunk is not None:
            expected = (
                batch,
                self.prediction_horizon,
                layout.action_dim,
            )
            if initial_action_chunk.shape != expected:
                raise ValueError(
                    f"initial action chunk must have shape {expected}"
                )
            previous = observation["action"][:, -1, : layout.action_dim]
            prior = initial_action_chunk
            if self.predict_vector_residuals:
                prior = prior - previous[:, None]
            action_slot = layout.action_index
            action_noise = torch.randn_like(prior) * float(
                action_prior_noise_scale
            )
            values[:, :, action_slot, : layout.action_dim] = (
                prior + action_noise
            )
        if deterministic_action:
            action_slot = layout.action_index
            values[:, :, action_slot, : layout.action_dim] = 0
        valid = torch.ones(values.shape[:-1], device=values.device, dtype=values.dtype)
        tactile_slots = layout.slices()["tactile"]
        # Touch remains structurally present but is invalid until a sensor is connected.
        if not observation["tactile_valid"].any():
            valid[:, :, tactile_slots] = 0
        change_gates = self._change_gates(observation)
        prefix_cache = None
        for index in range(steps):
            timestep = torch.full(
                (batch,), (index + 0.5) / steps, device=values.device, dtype=values.dtype
            )
            use_cache = (
                cache_refresh_steps is not None
                and index not in cache_refresh_steps
                and prefix_cache is not None
                and cache_depth > 0
            )
            conditional_result = self._predict_velocity(
                context,
                values,
                valid,
                timestep,
                text_ids,
                change_gates=change_gates,
                prefix_cache=prefix_cache if use_cache else None,
                cache_depth=cache_depth,
                return_prefix_cache=cache_depth > 0 and not use_cache,
            )
            if cache_depth > 0 and not use_cache:
                conditional, prefix_cache = conditional_result
            else:
                conditional = conditional_result
            if guidance_scale != 1.0:
                unconditional = self._predict_velocity(
                    context,
                    values,
                    valid,
                    timestep,
                    text_ids,
                    drop_condition=True,
                    change_gates=change_gates,
                )
                conditional = unconditional + guidance_scale * (conditional - unconditional)
            values = values + conditional / steps
            values = values * layout.channel_mask(values.device, values.dtype)[None, None]
        values = self._apply_vector_residuals(values, observation, inverse=True)
        decoded = self.tokenizer.decode(values)
        if use_direct_action:
            direct_action = self._predict_direct_action(context, observation)
            decoded = DecodedFrames(
                vision=decoded.vision,
                tactile=decoded.tactile,
                proximity=decoded.proximity,
                robot_state=decoded.robot_state,
                action=direct_action,
                full_hand_tactile_latent=decoded.full_hand_tactile_latent,
            )
        if self.contact_gated_pressure and layout.action_dim >= 7:
            action = decoded.action.clone()
            contact = observation["tactile_valid"][:, -1].to(action.dtype)
            action[:, :, 6] *= contact[:, None]
            decoded = DecodedFrames(
                vision=decoded.vision,
                tactile=decoded.tactile,
                proximity=decoded.proximity,
                robot_state=decoded.robot_state,
                action=action,
                full_hand_tactile_latent=decoded.full_hand_tactile_latent,
            )
        return decoded
